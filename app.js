function openPage(page) {

    if (page === "zoeken") {
        alert("Hier kun je iemand zoeken.");
    }

    else if (page === "videogesprekken") {
        alert("Hier vind je jouw videogesprekken.");
    }

    else if (page === "afspraken") {
        alert("Hier vind je jouw afspraken.");
    }

    else if (page === "profiel") {
        alert("Hier kun je jouw profiel bekijken.");
    }

    else if (page === "instellingen") {
        alert("Hier kun je de instellingen aanpassen.");
    }

}